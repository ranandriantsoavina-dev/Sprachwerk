import type { Question, QuestionMatchingPair } from '../../types/domain';

function pairsToAnswer(pairs: QuestionMatchingPair[]): string {
  return pairs.map((p) => `${p.left} -> ${p.right}`).join(' | ');
}

function makeMatchingQuestion(
  id: string,
  learningObjectiveId: string,
  topicTags: string[],
  promptDe: string,
  promptEn: string,
  promptFr: string,
  pairs: QuestionMatchingPair[],
  explanation_i18n: Record<string, string>
): Question {
  const answer = pairsToAnswer(pairs);
  return {
    id,
    mode: 'lesson-practice',
    lesson_ids: ['a1-01'],
    topic_tags: topicTags,
    learning_objective_id: learningObjectiveId,
    cefr_level: 'A1',
    difficulty: 'easy',
    type: 'matching',
    prompt_de: promptDe,
    prompt_i18n: {
      en: promptEn,
      fr: promptFr,
      de: promptDe,
    },
    matching_pairs: pairs,
    solution: answer,
    accepted_answers: [answer],
    explanation_i18n,
    source_language: 'de',
  };
}

